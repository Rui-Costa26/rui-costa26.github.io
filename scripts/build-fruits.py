"""One-off generator. Usage:
  python3 scripts/build-fruits.py <path to Fruidoku/tools/design/fruit_shapes.py> <path to levels.json>
Writes src/components/FruitSprite.astro (SVG symbols, white variant used on board tiles)
and src/demo/levels.ts (two real catalogue levels)."""
import sys, json, importlib.util, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location('fruit_shapes', sys.argv[1])
fs = importlib.util.module_from_spec(spec); spec.loader.exec_module(fs)
FRUITS = ['cherry', 'orange', 'banana', 'blueberry', 'grape', 'pear']
syms = []
for name in FRUITS:
    w = fs.fruit(name, fill='#FFFFFF', detail='DETAIL', leaf_color='#FFFFFF')
    w = w.replace('fill="DETAIL"', 'style="fill:var(--tile)"').replace('stroke="DETAIL"', 'style="stroke:var(--tile)"')
    syms.append(f'<symbol id="fw-{name}" viewBox="0 0 100 100">{w}</symbol>')
(root / 'src/components/FruitSprite.astro').write_text(
    '---\n// Generated by scripts/build-fruits.py from the Fruidoku app\'s fruit_shapes.py. Do not edit by hand.\n---\n'
    '<svg width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false"><defs>' + ''.join(syms) + '</defs></svg>\n')
levels = sorted(json.load(open(sys.argv[2]))['levels'], key=lambda l: l['order'])
pick = [levels[0], levels[8]]
body = json.dumps([{k: l[k] for k in ('id', 'size', 'regions', 'solution')} for l in pick], indent=2)
(root / 'src/demo/levels.ts').write_text(
    "// Generated by scripts/build-fruits.py: real levels from the Fruidoku catalogue (levels.json).\n"
    "export interface Level { id: string; size: number; regions: number[][]; solution: number[] }\n"
    f"export const LEVELS: Level[] = {body};\n")
print('ok', [l['id'] for l in pick])
